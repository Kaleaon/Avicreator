//! GLSL emission for interactive raymarched previews, plus the viewer page.
//!
//! The emitted code defines `float map(vec3 p)` (signed distance),
//! `vec3 partColor(vec3 p)` (soft part-membership colours, the same weighting
//! used for skinning), `float influence(vec3 p, int bone)` (one bone's weight
//! field before the four-bone limit) and `vec2 boneMap(vec3 p)` (distance,
//! bone id) for the skeleton overlay. Formulas mirror `sdf.rs` and `field.rs`.

use std::fmt::Write;

use avicreator_core::{Quat, Vec3};
use serde_json::{json, Value};

use crate::compile::{CompiledShape, Influence};
use crate::program::{Op, ShapeProgram};
use crate::sdf::Shape;

const PRELUDE: &str = r#"float smin(float a, float b, float k) {
  if (k <= 0.0) return min(a, b);
  float h = max(k - abs(a - b), 0.0) / k;
  return min(a, b) - h * h * k * 0.25;
}
float smax(float a, float b, float k) { return -smin(-a, -b, k); }
float dot2(vec3 v) { return dot(v, v); }
float sdRoundCone(vec3 p, vec3 a, vec3 b, float r1, float r2) {
  vec3 ba = b - a; float l2 = dot(ba, ba); float rr = r1 - r2;
  float a2 = l2 - rr * rr; float il2 = 1.0 / l2;
  vec3 pa = p - a; float y = dot(pa, ba); float z = y - l2;
  float x2 = dot2(pa * l2 - ba * y); float y2 = y * y * l2; float z2 = z * z * l2;
  float k = sign(rr) * rr * rr * x2;
  if (sign(z) * a2 * z2 > k) return sqrt(x2 + z2) * il2 - r2;
  if (sign(y) * a2 * y2 < k) return sqrt(x2 + y2) * il2 - r1;
  return (sqrt(x2 * a2 * il2) + y * rr) * il2 - r1;
}
float sdEllipsoid(vec3 p, vec3 r) {
  float k0 = length(p / r); float k1 = length(p / (r * r));
  return k0 * (k0 - 1.0) / k1;
}
float udTriangle(vec3 p, vec3 a, vec3 b, vec3 c) {
  vec3 ba = b - a; vec3 pa = p - a; vec3 cb = c - b; vec3 pb = p - b;
  vec3 ac = a - c; vec3 pc = p - c; vec3 nor = cross(ba, ac);
  return sqrt((sign(dot(cross(ba, nor), pa)) + sign(dot(cross(cb, nor), pb)) +
               sign(dot(cross(ac, nor), pc)) < 2.0)
    ? min(min(dot2(ba * clamp(dot(ba, pa) / dot2(ba), 0.0, 1.0) - pa),
              dot2(cb * clamp(dot(cb, pb) / dot2(cb), 0.0, 1.0) - pb)),
              dot2(ac * clamp(dot(ac, pc) / dot2(ac), 0.0, 1.0) - pc))
    : dot(nor, pa) * dot(nor, pa) / dot2(nor));
}
"#;

fn f(x: f32) -> String {
    format!("{:.4}", x)
}

fn v(p: Vec3) -> String {
    format!("vec3({},{},{})", f(p.x), f(p.y), f(p.z))
}

fn shape_call(shape: &Shape) -> String {
    match shape {
        Shape::RoundCone { a, b, ra, rb } => {
            let l = b.sub(*a).length();
            if l * l - (ra - rb) * (ra - rb) <= 1e-12 {
                let (c, r) = if ra >= rb { (*a, *ra) } else { (*b, *rb) };
                format!("length(p-{})-{}", v(c), f(r))
            } else {
                format!("sdRoundCone(p,{},{},{},{})", v(*a), v(*b), f(*ra), f(*rb))
            }
        }
        Shape::Ellipsoid { center, rot, radii } => {
            let local = if rot.dot(Quat::IDENTITY).abs() > 1.0 - 1e-7 {
                format!("p-{}", v(*center))
            } else {
                let inv = rot.conjugate();
                let (c0, c1, c2) = (inv.rotate_vec3(Vec3::X), inv.rotate_vec3(Vec3::Y), inv.rotate_vec3(Vec3::Z));
                format!("mat3({},{},{})*(p-{})", v(c0), v(c1), v(c2), v(*center))
            };
            format!("sdEllipsoid({},{})", local, v(*radii))
        }
        Shape::Slab { a, b, c, half_thickness } => {
            format!("udTriangle(p,{},{},{})-{}", v(*a), v(*b), v(*c), f(*half_thickness))
        }
    }
}

/// Emits the GLSL ES 3.0 functions described in the module docs.
pub fn emit_glsl(shape: &CompiledShape) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// {} — generated by avicreator-shape; edit the program, not this file.", shape.name);
    out.push_str(PRELUDE);

    for (i, part) in shape.parts.iter().enumerate() {
        let _ = writeln!(out, "// {} ({})\nfloat part{}(vec3 p) {{", part.name, part.kind, i);
        let prims = &shape.prims[part.prims.clone()];
        if prims.len() == 1 {
            let _ = writeln!(out, "  return {};", shape_call(&prims[0].shape));
        } else {
            let _ = writeln!(out, "  float d = {};", shape_call(&prims[0].shape));
            for prim in &prims[1..] {
                if part.smooth > 0.0 {
                    let _ = writeln!(out, "  d = smin(d, {}, {});", shape_call(&prim.shape), f(part.smooth));
                } else {
                    let _ = writeln!(out, "  d = min(d, {});", shape_call(&prim.shape));
                }
            }
            out.push_str("  return d;\n");
        }
        out.push_str("}\n");
    }

    // Twin of `CompiledShape::distance`: smooth blending inside each group,
    // fillets into partner groups, hard union between groups, then the
    // unattached cuts. Far parts with three or more primitives are replaced
    // by their bounding-sphere distance, a lower bound that cannot change the
    // result near the surface because it exceeds every blend radius.
    out.push_str("float fil(float a, float b, float k) { return smin(a, b, k); }\n");
    out.push_str("float map(vec3 p) {\n  float dp, b;\n");
    if !shape.groups.is_empty() {
        let decl: Vec<String> = (0..shape.groups.len()).map(|g| format!("g{} = 1e10", g)).collect();
        let _ = writeln!(out, "  float {};", decl.join(", "));
    }
    let kmax = shape.parts.iter().map(|p| p.blend + p.smooth).fold(0.0, f32::max);
    let far = 2.0 * kmax + 2e-3;
    let mut cuts = Vec::new();
    for (i, part) in shape.parts.iter().enumerate() {
        if part.prims.len() >= 3 {
            let c = part.bounds.center();
            let r = part.bounds.size().length() * 0.5;
            let _ = writeln!(out, "  b = length(p-{})-{}; dp = b < {} ? part{}(p) : b;", v(c), f(r), f(far), i);
        } else {
            let _ = writeln!(out, "  dp = part{}(p);", i);
        }
        match (part.group, part.op) {
            (Some(g), Op::Union) => {
                let _ = writeln!(out, "  g{g} = smin(g{g}, dp, {});", f(part.blend), g = g);
            }
            (Some(g), Op::Subtract) => {
                let _ = writeln!(out, "  g{g} = smax(g{g}, -dp, {});", f(part.blend), g = g);
            }
            (None, _) => {
                let _ = writeln!(out, "  float cut{} = dp;", i);
                cuts.push(i);
            }
        }
    }
    out.push_str("  float d = 1e10;\n");
    for (gi, group) in shape.groups.iter().enumerate() {
        let mut expr = format!("g{}", gi);
        for &h in &group.partners {
            expr = format!("min({}, fil(g{}, g{}, {}))", expr, gi, h, f(group.blend));
        }
        let _ = writeln!(out, "  d = min(d, {});", expr);
    }
    for i in cuts {
        let _ = writeln!(out, "  d = smax(d, -cut{}, {});", i, f(shape.parts[i].blend));
    }
    out.push_str("  return d;\n}\n");

    emit_visibility(shape, &mut out);

    let colored: Vec<usize> = shape
        .parts
        .iter()
        .enumerate()
        .filter(|(_, p)| p.op == Op::Union)
        .map(|(i, _)| i)
        .collect();
    out.push_str("vec3 partColor(vec3 p) {\n");
    for &i in &colored {
        let _ = writeln!(out, "  float d{} = part{}(p);", i, i);
    }
    let min_expr = colored.iter().map(|i| format!("d{}", i)).reduce(|a, b| format!("min({},{})", a, b));
    let _ = writeln!(out, "  float m = {};\n  vec3 c = vec3(0.0); float w = 0.0; float e;", min_expr.unwrap_or_else(|| "0.0".into()));
    for &i in &colored {
        let part = &shape.parts[i];
        let [r, g, b] = part.color;
        let _ = writeln!(
            out,
            "  e = exp(-(d{i} - m) / {}); {}c += e * vec3({},{},{}); w += e;",
            f(part.membership_softness()),
            visible(shape, i, &colored),
            f(r),
            f(g),
            f(b),
            i = i
        );
    }
    out.push_str("  return c / max(w, 1e-6);\n}\n");

    emit_influence(shape, &mut out);

    let size = shape.bounds.size();
    let scale = size.x.max(size.y).max(size.z);
    out.push_str("vec2 boneMap(vec3 p) {\n  vec2 r = vec2(1e10, -1.0); float d;\n");
    for (i, bone) in shape.bones.iter().enumerate() {
        let len = bone.tail.sub(bone.head).length();
        let r = (len * 0.07).min(scale * 0.006).max(scale * 0.0015);
        let _ = writeln!(
            out,
            "  d = sdRoundCone(p,{},{},{},{}); if (d < r.x) r = vec2(d, {}.0);",
            v(bone.head),
            v(bone.tail),
            f(r),
            f(r * 0.35),
            i
        );
    }
    out.push_str("  return r;\n}\n");
    out
}

/// Statement attenuating `e` by part `i`'s visibility when a part it is not
/// blend-connected to owns the point (twin of the test in `weights`).
fn visible(shape: &CompiledShape, i: usize, owners: &[usize]) -> String {
    let unconnected: Vec<String> = owners
        .iter()
        .filter(|&&o| o != i && !shape.blend_connected(o, i))
        .map(|o| format!("d{} == m", o))
        .collect();
    if shape.influence_bones(i).is_empty() || unconnected.is_empty() {
        String::new()
    } else {
        format!("if (e >= 1e-4 && d{i} > m && ({})) e *= vis{i}(p); ", unconnected.join(" || "), i = i)
    }
}

/// `vis<i>(p)`: twin of `CompiledShape::visibility`.
fn emit_visibility(shape: &CompiledShape, out: &mut String) {
    out.push_str("vec3 segPoint(vec3 p, vec3 a, vec3 b) {\n  vec3 ab = b - a;\n  return a + ab * clamp(dot(p - a, ab) / dot(ab, ab), 0.0, 1.0);\n}\n");
    for i in 0..shape.parts.len() {
        let bones = shape.influence_bones(i);
        if bones.is_empty() || shape.parts[i].op != Op::Union {
            continue;
        }
        let _ = writeln!(out, "float vis{}(vec3 p) {{\n  vec3 a = p, c; float bd = 1e10, t;", i);
        for b in bones {
            let bone = &shape.bones[b];
            let _ = writeln!(out, "  c = segPoint(p,{},{}); t = dot2(p - c); if (t < bd) {{ bd = t; a = c; }}", v(bone.head), v(bone.tail));
        }
        let _ = writeln!(
            out,
            "  float mf = -1e10;\n  for (int s = 1; s <= {n}; s++) mf = max(mf, map(mix(p, a, float(s) / {}.0)));\n  return clamp(1.0 - mf / {}, 0.0, 1.0);\n}}",
            crate::field::VISIBILITY_SAMPLES + 1,
            f(shape.visibility_width(i)),
            n = crate::field::VISIBILITY_SAMPLES
        );
    }
}

/// Mirrors `CompiledShape::weights` for a single bone, so the viewer can
/// paint any bone's influence field.
fn emit_influence(shape: &CompiledShape, out: &mut String) {
    let parts: Vec<usize> = shape
        .parts
        .iter()
        .enumerate()
        .filter(|(_, p)| p.op == Op::Union && !matches!(p.influence, Influence::None))
        .map(|(i, _)| i)
        .collect();

    out.push_str("float segDist(vec3 p, vec3 a, vec3 b) {\n  vec3 ab = b - a;\n  return length(p - a - ab * clamp(dot(p - a, ab) / dot(ab, ab), 0.0, 1.0));\n}\n");
    for &i in &parts {
        let part = &shape.parts[i];
        let _ = writeln!(out, "float share{}(vec3 p, int bone) {{", i);
        match &part.influence {
            Influence::None => out.push_str("  return 0.0;\n"),
            Influence::Rigid { bone } => {
                let _ = writeln!(out, "  return bone == {} ? 1.0 : 0.0;", bone);
            }
            Influence::PerPrimitive => {
                out.push_str("  float bd = 1e10; int bb = -1; float t;\n");
                for prim in &shape.prims[part.prims.clone()] {
                    if let Some(b) = prim.bone {
                        let _ = writeln!(out, "  t = {}; if (t < bd) {{ bd = t; bb = {}; }}", shape_call(&prim.shape), b);
                    }
                }
                out.push_str("  return bb == bone ? 1.0 : 0.0;\n");
            }
            Influence::Nearest { bones } => {
                out.push_str("  float s1 = 1e10, s2 = 1e10; int b1 = -1, b2 = -1; float t;\n");
                for &b in bones {
                    let bone = &shape.bones[b];
                    let _ = writeln!(
                        out,
                        "  t = segDist(p,{},{}); if (t < s1) {{ s2 = s1; b2 = b1; s1 = t; b1 = {}; }} else if (t < s2) {{ s2 = t; b2 = {}; }}",
                        v(bone.head),
                        v(bone.tail),
                        b,
                        b
                    );
                }
                out.push_str("  float w1 = 1.0 / (s1 * s1 + 1e-4); float w2 = b2 >= 0 ? 1.0 / (s2 * s2 + 1e-4) : 0.0;\n");
                out.push_str("  return ((bone == b1 ? w1 : 0.0) + (bone == b2 ? w2 : 0.0)) / (w1 + w2);\n");
            }
            Influence::Chain { bones, joints } => {
                let n = bones.len();
                let first = bones[0];
                debug_assert!(bones.iter().enumerate().all(|(k, &b)| b == first + k), "chain bones are contiguous");
                let list = joints.iter().map(|&j| v(j)).collect::<Vec<_>>().join(",");
                let _ = writeln!(out, "  if (bone < {} || bone >= {}) return 0.0;", first, first + n);
                let _ = writeln!(out, "  vec3 J[{}] = vec3[{}]({});", n + 1, n + 1, list);
                out.push_str("  float best = 1e10; int seg = 0; float u = 0.0;\n");
                let _ = writeln!(
                    out,
                    "  for (int i = 0; i < {}; i++) {{ vec3 ab = J[i + 1] - J[i]; float t = clamp(dot(p - J[i], ab) / dot(ab, ab), 0.0, 1.0); float d = dot2(p - J[i] - ab * t); if (d < best) {{ best = d; seg = i; u = t; }} }}",
                    n
                );
                let _ = writeln!(out, "  int k = bone - {}; float hw = {};", first, f(shape.settings.joint_blend * 0.5));
                out.push_str("  if (hw > 0.0 && u < hw && seg > 0) { float t = smoothstep(-hw, hw, u); return k == seg ? t : (k == seg - 1 ? 1.0 - t : 0.0); }\n");
                let _ = writeln!(
                    out,
                    "  if (hw > 0.0 && u > 1.0 - hw && seg + 1 < {}) {{ float t = smoothstep(-hw, hw, u - 1.0); return k == seg ? 1.0 - t : (k == seg + 1 ? t : 0.0); }}",
                    n
                );
                out.push_str("  return k == seg ? 1.0 : 0.0;\n");
            }
        }
        out.push_str("}\n");
    }

    out.push_str("float influence(vec3 p, int bone) {\n");
    for &i in &parts {
        let _ = writeln!(out, "  float d{} = part{}(p);", i, i);
    }
    let min_expr = parts.iter().map(|i| format!("d{}", i)).reduce(|a, b| format!("min({},{})", a, b));
    let _ = writeln!(out, "  float m = {};\n  float W = 0.0, w = 0.0, e;", min_expr.unwrap_or_else(|| "0.0".into()));
    for &i in &parts {
        let _ = writeln!(
            out,
            "  e = exp(-(d{i} - m) / {}); {}if (e >= 1e-4) {{ W += e; w += e * share{i}(p, bone); }}",
            f(shape.parts[i].membership_softness()),
            visible(shape, i, &parts),
            i = i
        );
    }
    out.push_str("  return W > 0.0 ? w / W : 0.0;\n}\n");
}

/// Everything a viewer needs besides the shader: parameters with slider
/// ranges, parts, bones and size statistics.
pub fn meta(program: &ShapeProgram, shape: &CompiledShape, program_bytes: usize, glsl_bytes: usize) -> Value {
    // Shortest decimal form, so 1.6f32 reaches the page as 1.6 rather than 1.600000023841858.
    let clean = |x: f32| x.to_string().parse::<f64>().unwrap_or(x as f64);
    let params: Vec<Value> = program
        .params
        .iter()
        .map(|(name, p)| {
            let (min, max) = p.range();
            json!({ "name": name, "value": clean(p.value()), "min": clean(min), "max": clean(max) })
        })
        .collect();
    let parts: Vec<Value> = shape
        .parts
        .iter()
        .map(|p| {
            json!({
                "name": p.name, "kind": p.kind, "color": p.color,
                "op": if p.op == Op::Union { "union" } else { "subtract" },
                "primitives": p.prims.len(),
            })
        })
        .collect();
    let bones: Vec<Value> = shape
        .bones
        .iter()
        .map(|b| {
            json!({
                "name": b.name, "parent": b.parent, "part": shape.parts[b.part].name,
                "head": b.head.to_array(), "tail": b.tail.to_array(),
                "limits": { "bend": b.limits.bend, "side": b.limits.side, "twist": b.limits.twist },
            })
        })
        .collect();
    let ground = shape
        .parts
        .iter()
        .filter(|p| p.op == Op::Union)
        .map(|p| p.bounds.min.y)
        .fold(f32::INFINITY, f32::min);
    json!({
        "name": shape.name,
        "params": params,
        "ground": ground,
        "parts": parts,
        "bones": bones,
        "bounds": { "min": shape.bounds.min.to_array(), "max": shape.bounds.max.to_array() },
        "resolution": shape.settings.resolution,
        "stats": {
            "program_bytes": program_bytes,
            "glsl_bytes": glsl_bytes,
            "parts": shape.parts.len(),
            "primitives": shape.prims.len(),
            "bones": shape.bones.len(),
        },
    })
}

const VIEWER: &str = include_str!("viewer.html");

/// The viewer page. With `embed` (shader + meta) it is a standalone preview;
/// without, it runs as Shape Studio against the `avishape studio` API.
pub fn viewer_html(embed: Option<(&str, &Value)>) -> String {
    let payload = match embed {
        Some((glsl, meta)) => json!({ "glsl": glsl, "meta": meta }).to_string().replace("</", "<\\/"),
        None => "null".to_string(),
    };
    VIEWER.replace("/*__EMBED__*/null", &payload)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::compile::compile;

    #[test]
    fn glsl_defines_one_function_per_part_and_the_entry_points() {
        let program = ShapeProgram::from_json(
            r#"{"parts":[
                {"kind":"chain","name":"body","from":[0,1,0],"dir":[0,0,1],"length":1,"segments":3,"radius":0.3},
                {"kind":"blob","name":"head","attach":"body","axis":[0,-0.3,1],"radii":[0.2,0.2,0.3],"separate":true},
                {"kind":"blob","name":"eye","mirror":true,"op":"subtract","attach":"head","offset":[0.1,0.1,0.1],"radii":0.04}
            ]}"#,
        )
        .unwrap();
        let shape = compile(&program).unwrap();
        let glsl = emit_glsl(&shape);
        for needle in [
            "float part0(", "float part3(", "float map(vec3 p)", "vec3 partColor(vec3 p)", "vec2 boneMap(vec3 p)",
            "float influence(vec3 p, int bone)", "float share0(", "g1 = smax(g1, -dp", "fil(g1, g0", "mat3(",
        ] {
            assert!(glsl.contains(needle), "missing {}", needle);
        }
        assert!(!glsl.contains("NaN") && !glsl.contains("inf,") && !glsl.contains("inf)"));

        let meta = meta(&program, &shape, 10, glsl.len());
        assert!(meta["params"].as_array().unwrap().is_empty());
        assert_eq!(meta["bones"].as_array().unwrap().len(), 4);
        let html = viewer_html(Some((&glsl, &meta)));
        assert!(html.contains("float map(vec3 p)") && !html.contains("/*__EMBED__*/"));
        assert!(html.contains(r#"canvas id="view" tabindex="0" role="img" aria-label="3D Model Viewer""#));
        assert!(html.contains(r#"aria-description="Use arrow keys or WASD to orbit"#));
        assert!(html.contains(r#"ul class="list bones" id="bones" role="listbox" aria-label="Skeleton bones""#));
        assert!(html.contains(r#"li.setAttribute("role", "option")"#));
        assert!(html.contains(r#"li.setAttribute("aria-selected","#));
    }
}
